"""Write the starter sentinel-config tree `config/starter/` from the spec's appendix tables (12-starter-registry-absent).

    python tools/gen_starter.py [--out DIR] [--check]

What it writes, and from where:

- `registry/surfaces/<area>/<id>.yaml`: one stub per 12.4 row, the spread and Advanced ticket rows expanded to one
  surface per value (14 and 5), tier 1, with the row's primitives, S flag, data mode, entitlement and personas; and a
  tier-2 stub for every other surface a 12.9 edge names (12.4: the tier-2 surfaces of 2.2.2 "are the next rows of
  the committed file"), with the primitives its edges give.
- `registry/dependency-map.yaml`: the 12.9 YAML block verbatim (10 primitives, 164 edges), plus the edges 12.9 omits
  "for length": every other spread and Advanced value takes the edges of `trade.order-entry.spread.vertical` and
  `ticket.advanced.oco`.
- `canaries/mutants.yaml`: M01 to M33 in the `{schema_version, entries}` form (SD-47), each bound to its 12.5
  checkpoint with its 12.5 class and money_cell; M25 binds `"*"` (SD-43).
- `diff_engine.yaml`: the harness's Diff Engine parameters, which 4.1 places at the root of sentinel-config.

`--check` regenerates into a temporary directory and fails when `config/starter/` differs (the CI form).

The stubs carry what the tables give; the rest needs the real app on the rig (4.5 says so per field: templates and
landmarks are captures, `roots` and the `[confirm from source]` primitives need source access, `resizable` and
`hosts` come from probe P8, kinds and titles from probes P1 to P8). So the starter lints clean of schema and
dependency-map errors (L-DEP-05 included) and fails only rules that need those Phase 0 inputs (tests/test_gen_starter.py
lists them). Choices (reported):

1. Kind: `dialog` for `dialog.*` and rows annotated "(dialog)", `context_menu` for `menu.*`, `settings_page` for
   `settings.*`, `ticket_variant` for `trade.order-entry.*` and `ticket.advanced.*`, `active_trader_panel` for the
   two ladders, `gadget` for `sidebar.*` and Flexible Grid cells, `panel` for the other Active Trader parts and
   tickets, `section` otherwise; a stub's title is its id until probe P2 reads the label.
2. Personas: all five (every 12.4 cell is at least `C`), ordered `F$` cells first, then `F`, then `C`, each in
   column order, so the primary persona (4.5 `personas[0]`) is the first money-flow persona.
3. Data mode is the first mode the row names (DR-02 branch A); entitlement the first entitlement named (`none` is
   no entitlement), and `options_L3` for the spread value `back-ratio`, the uncovered leg 12.4 names.
4. `resizable` is the S flag; a resizable stub's hosts are `flexgrid` for a Flexible Grid cell, `tab, flexgrid,
   detached` for the Active Trader ladder (the 4.5 worked example), `dialog` for a dialog and `detached` otherwise,
   placeholders until probe P8 measures them (2.5.1).
5. The mutant entries take their name, mode, generator and expected outcome from the example catalog
   (`config/example/canaries/mutants.yaml`, the same 12.5 rows), then the 12.5 binding, class and money_cell; M13
   and M14 expect `assertion_failed (assertion: R04)` as 12.5 says, `region_ref` is dropped (no regions file exists
   yet) and M28 drives `flow.canary.gateway`, the flow its 12.5 checkpoint names.
6. The 12.9 primitive lines are not valid YAML flow mappings (descriptions such as "Detach, dock and tab-host
   behavior" hold unquoted commas), so they are read field by field; the edge lines are read as YAML.
7. Files whose values the spec fixes are written too: `policy/budgets.yaml` (11.4), `soak.yaml` (10.11),
   `policy/explorer_budget.yaml` (6.8), and, copied from the example where it holds the spec's rows unchanged,
   `registry/ladders.yaml` (2.5.2) and `popups/catalog.yaml` (12.8). Team files (CODEOWNERS, ops/, the
   authorization, gateway and Phase 0 files) are left to the team. A stub's path is the wait for its landmark
   (L-SRF-05); the navigation before it is recorded at Phase 0.
"""
from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec_tables as st  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "config" / "starter"
EXAMPLE_MUTANTS = ROOT / "config" / "example" / "canaries" / "mutants.yaml"
DIFF_PARAMS = ROOT / "config" / "diff_engine.yaml"
PERSONAS = ("active_trader", "options_trader", "futures_trader", "swing_trader", "beginner")
GLOBAL = ("Theme", "FontMetrics")
SLUG = re.compile(r"^[a-z][a-z0-9-]*(\.[a-z0-9-]+)*$")
ENTITLEMENTS = ("margin", "options_L1", "options_L2", "options_L3", "futures", "forex", "ira", "portfolio_margin",
                "multi_account", "paper_send")
HEADER = "# Starter stub generated by tools/gen_starter.py from {src}; do not edit by hand before Phase 0.\n"
# files the example holds exactly as the spec tables give them (choice 7): the 2.5.2 ladders and the 12.8 catalog
COPIED = ("registry/ladders.yaml", "popups/catalog.yaml")


def _ticks(text: str) -> list[str]:
    return st.CODE.findall(text)


def _primitives(cell: str) -> list[str]:
    """The PascalCase primitive ids of a 12.4 primitives cell, annotations (`[verify]`, `[P8]`) dropped."""
    return re.findall(r"\b([A-Z][A-Za-z0-9]+)\b", re.sub(r"`[^`]*`", "", cell))


def _surface_ids(cell: str) -> list[str]:
    """The surface ids of a 12.4 first cell: one id, or one per value of a `<value>` row."""
    head = cell.split("(", 1)[0]
    ticks = [t for t in _ticks(head) if not t.startswith("[")]
    first = ticks[0]
    if "<value>" not in first:
        return [first]
    return [first.replace("<value>", v) for v in ticks[1:] if SLUG.match(v)]


def _personas(cells: list[str]) -> list[str]:
    def rank(i: int) -> tuple[int, int]:
        c = cells[i]
        return (0 if "F$" in c else 1 if re.search(r"\bF\b", c) else 2, i)
    return [PERSONAS[i] for i in sorted(range(len(PERSONAS)), key=rank)]


def _kind(sid: str, annotation: str) -> str:
    if sid.startswith("dialog.") or "(dialog)" in annotation:
        return "dialog"
    if sid.startswith("menu."):
        return "context_menu"
    if sid.startswith("settings."):
        return "settings_page"
    if sid.startswith(("trade.order-entry.", "ticket.advanced.")):
        return "ticket_variant"
    if sid in ("trade.active-trader.ladder", "charts.flexible-grid.active-trader-cell"):
        return "active_trader_panel"
    if sid.startswith("sidebar.") or sid.startswith("charts.flexible-grid."):
        return "gadget"
    if sid.startswith(("trade.active-trader.", "ticket.")):
        return "panel"
    return "section"


def _hosts(sid: str, kind: str) -> list[str]:
    if sid.startswith("charts.flexible-grid."):
        return ["flexgrid"]
    if sid == "trade.active-trader.ladder":
        return ["tab", "flexgrid", "detached"]
    return ["dialog"] if kind == "dialog" else ["detached"]


def _entitlements(cell: str, sid: str) -> list[str]:
    if sid.endswith(".back-ratio"):
        return ["options_L3"]
    m = re.match(r"\s*([A-Za-z_0-9]+)", re.sub(r"`[^`]*`", "", cell))
    word = m.group(1) if m else "none"
    return [word] if word in ENTITLEMENTS else []


def _stub(sid: str, tier: int, primitives: list[str], swept: bool, data_mode: str, entitlements: list[str],
          personas: list[str], annotation: str = "") -> dict[str, Any]:
    kind = _kind(sid, annotation)
    area = sid.split(".", 1)[0]
    out: dict[str, Any] = {
        "schema_version": 1, "id": sid, "title": sid, "kind": kind, "tier": tier,
        "owner": f"tier-{tier}-flow-owner",
        "path": [{"id": "p1", "type": "wait_for", "anchor": {"landmark": "lm.header"}, "timeout_ms": 8000}],
        "primitives": primitives, "roots": [f"TBD.{area}"], "personas": personas,
        "entitlements": entitlements, "enumerable_by": "none", "resizable": swept,
    }
    if swept:
        out["hosts"] = _hosts(sid, kind)
    out["target_window"] = {"kind": "dialog" if kind == "dialog" else "popup" if kind == "context_menu" else "main"}
    out["data_mode"] = data_mode
    out["landmarks"] = [{"id": "lm.header", "template": f"registry/templates/{area}/{sid}.header.png",
                         "must_see": True}]
    out["anti_anchors"] = ["Loading"]
    out["labels"] = []
    out["controls"] = []
    out["settle"] = {"max_wait_ms": 8000}
    out["census"] = {"enabled": True, "workspaces": []}
    return out


def tier1_rows() -> list[dict[str, Any]]:
    """Every 12.4 row as a stub, the `<value>` rows expanded."""
    rows = st.table_after(st.subsection("12.4"), "| Surface id | Primitives")
    out = []
    for r in rows:
        prims = _primitives(r[1])
        swept = r[2].strip().lower().startswith("yes")
        mode = "masked_live" if r[3].strip().startswith("masked_live") else "frozen"
        personas = _personas(r[5:10])
        for sid in _surface_ids(r[0]):
            out.append(_stub(sid, 1, prims, swept, mode, _entitlements(r[4], sid), personas, r[0]))
    return out


_PRIMITIVE = re.compile(r"\{id: (\w+),\s+description: (.+?),\s+source_packages: \[(.*?)\],\s+owner: ([\w-]+)"
                        r"(,\s*global: true)?\}")


def dependency_map() -> dict[str, Any]:
    """The 12.9 block: its primitives (read line by line, since their unquoted descriptions hold commas that a YAML
    flow mapping would split, choice 6) and its edges (YAML)."""
    block = st.subsection("12.9").split("```yaml", 1)[1].split("```", 1)[0]
    head, edges = block.split("\nedges:", 1)
    prims = []
    for m in _PRIMITIVE.finditer(head):
        p = {"id": m.group(1), "description": m.group(2).strip(),
             "source_packages": [x.strip().strip('"') for x in m.group(3).split(",")], "owner": m.group(4)}
        if m.group(5):
            p["global"] = True
        prims.append(p)
    data = {"schema_version": 1, "primitives": prims, "edges": yaml.safe_load("edges:" + edges)["edges"]}
    for e in data["edges"]:
        for k in ("first_seen", "last_verified"):
            if not isinstance(e.get(k), str):
                e[k] = e[k].isoformat()
    return data


def expand_variants(dm: dict[str, Any], surfaces: list[str]) -> None:
    """Add the 12.9 edges "omitted for length": each spread and Advanced value takes its template value's edges."""
    have = {(e["primitive"], e["surface"]) for e in dm["edges"]}
    for prefix, template in (("trade.order-entry.spread.", "trade.order-entry.spread.vertical"),
                             ("ticket.advanced.", "ticket.advanced.oco")):
        edges = [e for e in dm["edges"] if e["surface"] == template]
        for sid in surfaces:
            if sid.startswith(prefix) and sid != template:
                for e in edges:
                    if (e["primitive"], sid) not in have:
                        dm["edges"].append({**e, "surface": sid})
                        have.add((e["primitive"], sid))


def tier2_rows(dm: dict[str, Any], known: set[str]) -> list[dict[str, Any]]:
    """A tier-2 stub for every surface a 12.9 edge names that 12.4 does not (module docstring)."""
    prims: dict[str, list[str]] = {}
    for e in dm["edges"]:
        if e["surface"] != "*" and e["surface"] not in known:
            prims.setdefault(e["surface"], []).append(e["primitive"])
    return [_stub(sid, 2, sorted(set(p)) + list(GLOBAL), False, "frozen", [], list(PERSONAS))
            for sid, p in sorted(prims.items())]


def mutants() -> dict[str, Any]:
    """M01 to M33 bound to their 12.5 checkpoints (choice 5)."""
    rows = {r[0].strip(): r for r in st.table_after(st.subsection("12.5"), "| Id | Class (10.3) |")}
    raw = yaml.safe_load(EXAMPLE_MUTANTS.read_text(encoding="utf-8"))
    entries = raw["entries"] if isinstance(raw, dict) else raw
    table = st.mutant_table_12_5()
    out = []
    for m in entries:
        mid = m["mutant_id"]
        row = rows[mid]
        cid = _ticks(row[2])[0] if _ticks(row[2]) else "*"
        cid = "*" if "'*'" in row[2] or cid.startswith("checkpoint_id") else cid
        entry = {k: v for k, v in m.items() if k != "region_ref"}
        entry["checkpoint_id"] = cid
        entry["class"], entry["money_cell"] = table[mid]
        if mid in ("M13", "M14"):
            entry["expected"] = {"outcomes": ["assertion_failed"], "assertion_id": "R04"}
        if mid == "M28":
            entry["canary_flow"] = "flow.canary.gateway"
        out.append(entry)
    return {"schema_version": 1, "entries": out}


def policy_files() -> list[tuple[str, dict[str, Any], str]]:
    """The files whose values the spec fixes (choice 7): the 11.4 caps, the 10.11 soak defaults and the 6.8 Explorer
    budgets."""
    sys.path.insert(0, str(ROOT / "src"))
    from sentinel.policy import BUDGET_CAPS_11_4, SOAK_DEFAULTS
    budgets = {"schema_version": 1, **{k: dict(v) for k, v in BUDGET_CAPS_11_4.items()}}
    soak = {"schema_version": 1, "budgets": {k: dict(v) for k, v in SOAK_DEFAULTS.items()}}
    explorer = {"schema_version": 1, "max_actions": 400, "max_minutes": 90, "max_no_change_actions": 20,
                "max_usd_per_session": BUDGET_CAPS_11_4["usd"]["per_explorer_session"],
                "max_usd_per_week": BUDGET_CAPS_11_4["usd"]["per_week"]}
    return [("policy/budgets.yaml", budgets, "11.4"), ("soak.yaml", soak, "10.11"),
            ("policy/explorer_budget.yaml", explorer, "6.8")]


def _dump(path: Path, data: Any, src: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(src=src) + yaml.safe_dump(data, sort_keys=False, width=120, allow_unicode=True),
                    encoding="utf-8")


def generate(out: Path) -> dict[str, int]:
    """Write the starter tree under `out`; returns counts for the caller."""
    t1 = tier1_rows()
    dm = dependency_map()
    expand_variants(dm, [s["id"] for s in t1])
    t2 = tier2_rows(dm, {s["id"] for s in t1})
    if out.exists():
        shutil.rmtree(out)
    for s in t1 + t2:
        _dump(out / "registry" / "surfaces" / s["id"].split(".", 1)[0] / f"{s['id']}.yaml", s,
              "12.4" if s["tier"] == 1 else "the 12.9 edges")
    _dump(out / "registry" / "dependency-map.yaml", dm, "12.9")
    _dump(out / "canaries" / "mutants.yaml", mutants(), "12.5")
    for rel, data, src in policy_files():
        _dump(out / rel, data, src)
    shutil.copy(DIFF_PARAMS, out / "diff_engine.yaml")
    for rel in COPIED:
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / "config" / "example" / rel, out / rel)
    return {"tier1": len(t1), "tier2": len(t2), "edges": len(dm["edges"]), "primitives": len(dm["primitives"])}


def _same_tree(a: Path, b: Path) -> bool:
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    if filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)[1:] != ([], []):
        return False
    return all(_same_tree(a / d, b / d) for d in cmp.common_dirs)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="gen_starter")
    p.add_argument("--out", default=str(OUT))
    p.add_argument("--check", action="store_true", help="fail when the committed tree differs from the spec")
    args = p.parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            generate(Path(tmp) / "starter")
            ok = Path(args.out).is_dir() and _same_tree(Path(tmp) / "starter", Path(args.out))
        print("config/starter is current" if ok else "config/starter differs from the spec: run tools/gen_starter.py")
        return 0 if ok else 1
    counts = generate(Path(args.out))
    print(f"wrote {args.out}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
